// Publish prepared models: compress build/<id>.glb with meshopt into web/public/models/<id>.glb and
// regenerate shared/meshes.ts from every build/<id>.json.
//   node tools/prep-garments/register.mjs
// Needs @gltf-transform/cli (installed outside the repo: GLTF_TRANSFORM=/path/to/gltf-transform).
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const build = join(here, "build");
const out = join(root, "web", "public", "models");
mkdirSync(out, { recursive: true });
const tool = process.env.GLTF_TRANSFORM ?? "gltf-transform";

const metas = readdirSync(build).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(join(build, f), "utf8")));
for (const m of metas) {
  const src = join(build, `${m.id}.glb`);
  if (!existsSync(src)) continue;
  const dst = join(out, `${m.id}.glb`);
  // Only re-compress what changed (several models get prepared in parallel).
  if (existsSync(dst) && statSync(dst).mtimeMs >= statSync(src).mtimeMs) continue;
  execFileSync(tool, ["meshopt", src, join(out, `${m.id}.glb`), "--level", "medium"], { stdio: "inherit" });
  if (m.fold && existsSync(join(build, m.fold))) copyFileSync(join(build, m.fold), join(out, m.fold));
}
// Model files whose build is gone stay out of meshes.ts (and out of the bundle once deleted).
const models = Object.fromEntries(metas.map((m) => [m.id, { url: `/models/${m.id}.glb`, ...(m.fold ? { fold: `/models/${m.fold}` } : {}), nodes: m.nodes, bounds: m.bounds, zones: m.zones, credit: m.credit }]));
const ts = `/**
 * Prepared base models for fashion templates (kind "mesh" parts), served from /models/<id>.glb.
 * GENERATED by tools/prep-garments/register.mjs from tools/prep-garments/build/*.json: edit
 * tools/prep-garments/models/<id>.json and re-run the pipeline instead of editing this file.
 * Each node is one named garment piece (body, sleeve_l, collar...); bounds and zones are in the
 * model frame (meters, Y up, +Z front), where a node sits when its part has an identity transform.
 */

export interface MeshZone {
  part: string;
  label: string;
  at?: [number, number, number];
  normal?: [number, number, number];
  path?: [number, number, number][];
  normals?: [number, number, number][];
  room?: [number, number];
  bend?: number;
}

export interface MeshModel {
  /** URL of the GLB under web/public. */
  url: string;
  /** The source model's baked normal map (folds, seams), sampled with the model's own UVs where _fold = 1. */
  fold?: string;
  /** Node names, each a separate selectable part. */
  nodes: string[];
  bounds: Record<string, { min: [number, number, number]; max: [number, number, number] }>;
  /** Attachment zones found on the surface by the prep script. */
  zones?: Record<string, MeshZone>;
  /** Source credit for ATTRIBUTION.md. */
  credit: string;
}

export const MESH_MODELS: Record<string, MeshModel> = ${JSON.stringify(models, null, 1)};
`;
writeFileSync(join(root, "shared", "meshes.ts"), ts);

// CC-BY requires credit: every prepared model's line goes into ATTRIBUTION.md.
const credits = metas.filter((m) => m.credit && !m.id.startsWith("_")).map((m) => `| \`${m.id}\` | ${m.credit} |`);
const md = `# Attribution

3D base models used by Wish it's fashion templates. Each was decimated, re-oriented, rescaled to real
size, split into named pieces and re-textured with our own fabric presets (tools/prep-garments).
Textures and HDRI: see [web/public/textures/CREDITS.md](web/public/textures/CREDITS.md) (all CC0).

| Model | Credit (title, author, source, license) |
|---|---|
${credits.join("\n")}
`;
writeFileSync(join(root, "ATTRIBUTION.md"), md);
console.log(`registered ${metas.length} model(s): ${metas.map((m) => m.id).join(", ")}`);
